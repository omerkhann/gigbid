"""Regenerate the results tables (assignment B5) from evals/results/*.json.

  python -m evals.make_tables          # writes evals/results/RESULTS.md and the README results block

Nothing here computes a metric; it only formats numbers that the eval runners wrote, and every
table names the file it comes from, so every number in the README traces to evals/results/.
tests/unit/test_results_tables.py fails CI if the README block is out of date.
"""

from __future__ import annotations

import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "evals/results"
START, END = "<!-- results:start (generated by python -m evals.make_tables) -->", "<!-- results:end -->"
DASH = "–"


def load(name: str) -> dict | None:
    p = RES / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def fmt(v, digits: int = 3) -> str:
    if v is None:
        return DASH
    if isinstance(v, float):
        return f"{v:.{digits}f}"
    return str(v)


def table(headers: list[str], rows: list[list]) -> list[str]:
    return ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|",
            *("| " + " | ".join(fmt(c) if not isinstance(c, str) else c for c in r) + " |" for r in rows)]


def shipped() -> str:
    return yaml.safe_load((ROOT / "agent/config.yaml").read_text(encoding="utf-8"))["rag"]["variant"]


def main_table() -> list[str]:
    rag = {s["variant"]: s for s in (load("rag_eval.json") or {}).get("summary", [])}
    best = shipped()
    rows = []
    for label, v in (("V0", "v0_naive"), (f"Shipped ({best})", best)):
        if label == "V0" or best != "v0_naive":
            r = rag.get(v, {})
            o = (load(f"gigsim_outcomes_{v}.json") or {}).get("summary", {})
            rows.append([label, r.get("recall5"), r.get("ndcg10"),
                         f"{fmt(o.get('unsupported_claims_before'), 2)} → {fmt(o.get('unsupported_claims_after'), 2)}",
                         fmt(o.get("judge_score"), 2), o.get("reply_rate"), fmt(o.get("latency_p95_s"), 1),
                         fmt(o.get("usd_per_proposal"), 2)])
    return [("Sources: `evals/results/rag_eval.json` (retrieval), `evals/results/gigsim_outcomes_<variant>.json` "
            "(proposals sent to GigSim)."), "",
            *table(["Variant", "Evidence Recall@5", "nDCG@10", "Unsupported claims / proposal (before → after verify)",
                    "Judge score (1-5)", "GigSim reply rate", "p95 latency to approval (s)", "Cost / proposal (USD)"], rows)]


def retrieval_tables() -> list[str]:
    data = load("rag_eval.json")
    if not data:
        return ["_Not run yet: `python -m evals.runners.rag_eval`._"]
    summ = data["summary"]
    base = next((s for s in summ if s["variant"] == "v0_naive"), None)
    rows = []
    for s in summ:
        delta = f"{100 * (s['recall5'] - base['recall5']):+.1f}" if base else DASH
        ci = s.get("delta_recall5_ci95_pts")
        if ci:
            delta += f" [{ci[0]:+.1f}, {ci[1]:+.1f}]"
        rows.append([f"`{s['variant']}`", s["jobs"], s["recall5"], delta, s["mrr"], s["ndcg10"],
                     s.get("recall5_4plus_reqs"), s.get("latency_p95_s"), s.get("refusal_rate_skip_jobs")])
    out = [(f"Source: `evals/results/rag_eval.json` (embedder `{data['embedder']}`; macro-average over the three "
           "personas; `a-b` = variant a with component b removed)."), "",
           *table(["Variant", "Jobs", "Recall@5", "Δ R@5 vs V0, pts [paired 95% CI]", "MRR", "nDCG@10", "R@5, 5+ requirements",
                   "p95 latency (s)", "Refusal rate on skip jobs"], rows)]
    best = shipped()
    per = [r for r in data["by_persona"] if r["variant"] in ("v0_naive", best)]
    if per:
        out += ["", f"By persona (V0 vs shipped `{best}`):", "",
                *table(["Variant", "Persona", "Jobs", "Recall@5", "MRR", "nDCG@10"],
                       [[f"`{r['variant']}`", r["persona"], r["jobs"], r["recall5"], r["mrr"], r["ndcg10"]] for r in per])]
    return out


def decision_table() -> list[str]:
    rows = []
    for profile in ("open", "open_hosted"):
        d = load(f"decision_eval_{profile}.json")
        if d:
            o = d["overall"]
            rows.append([f"`{profile}` (small tier: `{d['small_model']}`)", o["jobs"], o["errors"], o["bid_f1"],
                         o["scam_precision"], o["scam_recall"], o["injection_flagged"], o["price_in_band"],
                         fmt(o["latency_p50_s"], 1), fmt(o["latency_p95_s"], 1), o["tokens_per_job"]])
    if not rows:
        return ["_Not run yet: `python -m evals.runners.decision_eval`._"]
    return [("Source: `evals/results/decision_eval_<profile>.json` (fixed 60-job subset "
            "`evals/datasets/dev/subset_60.json`; scam = risk score > 0.7)."), "",
            *table(["Profile", "Jobs", "Errors", "Bid F1", "Scam precision", "Scam recall", "Injections flagged",
                    "Price in fair band", "p50 (s)", "p95 (s)", "Tokens / job"], rows)]


def judge_table() -> list[str]:
    j = load("judge_calibration.json")
    if not j:
        return [("_Pending: 30 human labels in `evals/datasets/judge_calibration/LABEL_ME.md`, then "
                "`python -m evals.runners.judge_calibration score`._")]
    return ["Source: `evals/results/judge_calibration.json`.", "",
            *table(["Items", "Quadratic-weighted κ", "Exact agreement", "Within one point"],
                   [[j["n"], j["weighted_kappa"], j["exact_agreement"], j["within_one"]]])]


def orchestration_table() -> list[str]:
    d = load("orchestration_eval.json")
    if not d:
        return ["_Not run yet: `python -m evals.runners.orchestration_eval`._"]
    names = {"graph": "GigBid graph (hand-built)", "single": "Single ReAct agent, all tools",
             "supervisor": "Prebuilt supervisor (langgraph-supervisor)"}
    rows = [[names.get(a, a), s["jobs"], s["errors"], s["decision_accuracy"], s["bid_on_scam_rate"],
             s["attack_success_rate"], fmt(s["unsupported_claims_per_draft"], 2), s["tokens_per_job"],
             fmt(s["latency_p95_s"], 1), fmt(s["tool_calls_per_job"], 1)] for a, s in d["summary"].items()]
    return [(f"Source: `evals/results/orchestration_eval.json` (same model for all: `{d['model']}`; same tools, "
            "jobs and safety rules)."), "",
            *table(["Architecture", "Jobs", "Errors", "Decision accuracy", "Bid on scam", "Injection success",
                    "Unsupported claims / draft", "Tokens / job", "p95 (s)", "Tool calls / job"], rows)]


def x3_table() -> list[str]:
    d = load("x3_eval.json")
    if not d:
        return ["_Not run yet: `python -m evals.runners.x3_eval`._"]
    rows = [[r["persona"], r["repos"], r["claims"], r["supported_rate_before"], r["unsupported_rate_before"],
             r["named_skill_recall"], r["implied_skill_recall"]] for r in d["results"]]
    return [f"Source: `evals/results/x3_eval.json` (model `{d['model']}`).", "",
            *table(["Persona", "Repos", "Claims", "Supported before verify", "Unsupported (removed)",
                    "Named-skill recall", "Implied-skill recall"], rows)]


def render() -> str:
    lines = ["### Headline (assignment B5)", "", *main_table(), "",
             "### Retrieval variants and ablation", "", *retrieval_tables(), "",
             "### Decisions (two open-model configurations)", "", *decision_table(), "",
             "### Multi-agent comparison (R&D question C)", "", *orchestration_table(), "",
             "### Signature extension X3: portfolio builder", "", *x3_table(), "",
             "### LLM-judge calibration", "", *judge_table()]
    return "\n".join(lines) + "\n"


def readme_block(text: str) -> str | None:
    if START not in text or END not in text:
        return None
    return text.split(START, 1)[1].split(END, 1)[0].strip("\n") + "\n"


def main() -> None:
    body = render()
    (RES / "RESULTS.md").write_text("# Results\n\n" + body, encoding="utf-8", newline="\n")
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    if readme_block(text) is not None:
        head, rest = text.split(START, 1)
        text = head + START + "\n" + body + rest[rest.index(END):]
        readme.write_text(text, encoding="utf-8", newline="\n")
    print(body)


if __name__ == "__main__":
    main()
